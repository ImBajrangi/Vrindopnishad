export const PixelIcon: React.FC<PixelIconProps> = ({
  name,
  color = '#38bdf8',
  size = 32,
  animated = true,
  interval = 400
}) => {
  const frames = PIXEL_FRAMES[name] || PIXEL_FRAMES.path;
  const totalFrames = frames.length;
  const [frameIdx, setFrameIdx] = useState(0);

  useEffect(() => {
    if (!animated || totalFrames <= 1) return;
    const timer = setInterval(() => {
      setFrameIdx((prev) => (prev + 1) % totalFrames);
    }, interval);
    return () => clearInterval(timer);
  }, [animated, totalFrames, interval]);

  const grid = frames[frameIdx] || frames[0];
  const cols = grid[0].length;
  const gap = 1.4;
  const cellSize = (size - gap * (cols - 1)) / cols;

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      fill="none"
      style={{ display: 'inline-block' }}
    >
      {grid.map((row, rIdx) =>
        row.map((val, cIdx) => {
          const x = cIdx * (cellSize + gap);
          const y = rIdx * (cellSize + gap);
          return (
            <rect
              key={`${rIdx}-${cIdx}`}
              x={x}
              y={y}
              width={cellSize}
              height={cellSize}
              rx={0.6}
              fill={val === 1 ? color : 'rgba(255, 255, 255, 0.05)'}
              opacity={val === 1 ? 1 : 0.15}
            />
          );
        })
      )}
    </svg>
  );
};

export default PixelIcon;
